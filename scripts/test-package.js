import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { gunzipSync } from 'node:zlib';
import { runInNewContext } from 'node:vm';

const npm = process.env.npm_execpath;
assert(npm, 'Run through npm run test:package');
mkdirSync('.tmp', { recursive: true });
const directory = process.env.PACKAGE_DESTINATION ? resolve(process.env.PACKAGE_DESTINATION) : mkdtempSync(resolve('.tmp/package-'));
mkdirSync(directory, { recursive: true });
const [packed] = JSON.parse(execFileSync(process.execPath, [npm, 'pack', '--ignore-scripts', '--json', '--pack-destination', directory], { encoding: 'utf8' }));
const files = packed.files.map(file => file.path);
for (const path of ['LICENSE', 'README.md', 'dist/instances.js', 'dist/auto.js', 'browser-build/nano-lightbox.min.js', 'browser-build/nano-lightbox.min.js.gz', 'browser-build/nano-lightbox.css']) assert(files.includes(path), `Missing ${path}`);
assert(!files.some(file => /^(src|tests|scripts|site-dist|node_modules|\.github)\//.test(file)), 'Development files must not enter the package');
const consumer = join(directory, 'consumer');
mkdirSync(consumer);
writeFileSync(join(consumer, 'package.json'), JSON.stringify({ private: true, type: 'module' }));
execFileSync(process.execPath, [npm, 'install', '--offline', '--ignore-scripts', '--no-audit', '--no-fund', '--no-package-lock', join(directory, packed.filename)], { cwd: consumer, stdio: 'pipe' });
const installed = join(consumer, 'node_modules/nano-lightbox');
for (const path of files.filter(path => path.startsWith('dist/') || path.startsWith('browser-build/'))) assert.deepEqual(readFileSync(join(installed, path)), readFileSync(resolve(path)), `Archive differs: ${path}`);
const script = readFileSync(join(installed, 'browser-build/nano-lightbox.min.js'));
assert.deepEqual(gunzipSync(readFileSync(join(installed, 'browser-build/nano-lightbox.min.js.gz'))), script);
const pkg = JSON.parse(readFileSync(join(installed, 'package.json'), 'utf8'));
assert(script.toString().startsWith(`/*! Nano Lightbox v${pkg.version} | MIT |`));
const context = {};
runInNewContext(script.toString(), context);
assert.equal(typeof context.NanoLightbox.createScope, 'function', 'Standalone script must expose its API without any imports');
assert(!/@import|url\(/.test(readFileSync(join(installed, 'browser-build/nano-lightbox.css'), 'utf8')), 'Browser CSS must be self-contained');
writeFileSync(join(consumer, 'smoke.mjs'), `
import assert from 'node:assert/strict';
import { access } from 'node:fs/promises';
import { createScope, getScope } from 'nano-lightbox/instances';
import { open, close } from 'nano-lightbox/core';
import { openGallery } from 'nano-lightbox/gallery';
import { resolveMedia } from 'nano-lightbox/providers';
import { createThumbs } from 'nano-lightbox/thumbs';
for (const fn of [createScope, getScope, open, close, openGallery, resolveMedia, createThumbs]) assert.equal(typeof fn, 'function');
for (const specifier of ['nano-lightbox', 'nano-lightbox/core.css', 'nano-lightbox/gallery.css', 'nano-lightbox/thumbs.css', 'nano-lightbox/nano-lightbox.js', 'nano-lightbox/browser-build/nano-lightbox.min.js', 'nano-lightbox/browser-build/nano-lightbox.css']) await access(new URL(import.meta.resolve(specifier)));
assert.equal(resolveMedia('https://example.com/photo.jpg').type, 'image');
`);
execFileSync(process.execPath, [join(consumer, 'smoke.mjs')], { stdio: 'inherit' });
console.log(`Package verified: ${join(directory, packed.filename)}`);
